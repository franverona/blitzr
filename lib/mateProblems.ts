// Hand-authored, not imported — same "hardcoded array, no DB table" pattern
// as lib/openingTheory.ts. Source: real tournament/match games ending in a
// forced mate, imported from a citation/FEN/solution list. The full move
// list (not just the key) is replayed through chess.js and confirmed to end
// in checkmate before being included; mate-in-2 entries are additionally
// verified with a brute-force search (does the key force mate in 2 against
// every legal reply?) — see import-mate2.mjs.
export interface MateProblem {
  id: number
  /** Position with the side to move about to force mate. */
  fen: string
  /** The full solution line in SAN, alternating solver/opponent/solver/...
   *  starting with the solver's own key move. PuzzleBoard has you play every
   *  ply by hand (both sides) — solved means you walked the whole recorded
   *  line yourself, not just found the first move. */
  moves: string[]
  /** How many of the side-to-move's own moves the mate takes — read off the
   *  solution's own move numbers, not assumed. */
  mateIn: number
  /** "White player vs Black player" — these are real games, not composed problems. */
  title: string
  composer: string
  source: string
  year: string
  /** Full solution line, shown after solving or on "reveal". */
  solution: string
}

